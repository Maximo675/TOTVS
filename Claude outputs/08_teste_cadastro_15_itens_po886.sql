-- Chamado Comex - relatorios perdidos SAP -> TOTVS
-- 08) TESTE AUTOCONFERIDO do cadastro: para os 15 produtos do modelo
--     "RASCUNHO DUIMP - PO 886.ENT.26", compara o que esta no cadastro (SB1)
--     com o que o Comex mandou no modelo: Codigo SAP (B1_ZCODSAP), NCM
--     (B1_POSIPI) e EX-tarifario (B1_EX_NCM = "Ex-NCM - determina % I.I.").
--     Valores esperados estao escritos abaixo (tirados do modelo); as colunas
--     *_OK dizem OK / DIVERGE por item. Nao depende do pedido 886 existir.
-- Normalizacao: NCM sem pontos; EX sem zeros a esquerda ('002' = '2');
-- EX vazio no modelo ('-') = vazio no cadastro.
-- Pode repetir linha se o SB1 for exclusivo por filial (por isso B1_FILIAL).
-- SOMENTE LEITURA. Apelidos <= 10 caracteres.
SELECT
    E.COD,
    B1.B1_FILIAL,
    B1.B1_DESC,
    E.SAP_ESP,
    B1.B1_ZCODSAP,
    CASE WHEN B1.B1_COD IS NULL THEN 'SEM CADAST'
         WHEN TRIM(B1.B1_ZCODSAP) = E.SAP_ESP THEN 'OK'
         ELSE 'DIVERGE' END AS SAP_OK,
    E.NCM_ESP,
    B1.B1_POSIPI,
    CASE WHEN B1.B1_COD IS NULL THEN 'SEM CADAST'
         WHEN REPLACE(TRIM(B1.B1_POSIPI), '.', '') = E.NCM_ESP THEN 'OK'
         ELSE 'DIVERGE' END AS NCM_OK,
    E.EX_ESP,
    B1.B1_EX_NCM,
    CASE WHEN B1.B1_COD IS NULL THEN 'SEM CADAST'
         WHEN NVL(LTRIM(TRIM(B1.B1_EX_NCM), '0'), '-') = NVL(E.EX_ESP, '-') THEN 'OK'
         ELSE 'DIVERGE' END AS EX_OK
FROM (
    SELECT 'RV-002-00015' AS COD, 'I009958' AS SAP_ESP, '84439950' AS NCM_ESP, '' AS EX_ESP FROM DUAL
    UNION ALL
    SELECT 'RV-002-00017' AS COD, 'I010481' AS SAP_ESP, '84439949' AS NCM_ESP, '2' AS EX_ESP FROM DUAL
    UNION ALL
    SELECT 'RV-002-00020' AS COD, 'I010897' AS SAP_ESP, '84439942' AS NCM_ESP, '' AS EX_ESP FROM DUAL
    UNION ALL
    SELECT 'RV-002-00021' AS COD, 'I012559' AS SAP_ESP, '84433299' AS NCM_ESP, '9' AS EX_ESP FROM DUAL
    UNION ALL
    SELECT 'RV-002-00023' AS COD, 'I013488' AS SAP_ESP, '84439942' AS NCM_ESP, '' AS EX_ESP FROM DUAL
    UNION ALL
    SELECT 'RV-002-00025' AS COD, 'I013954' AS SAP_ESP, '84439949' AS NCM_ESP, '' AS EX_ESP FROM DUAL
    UNION ALL
    SELECT 'RV-002-00028' AS COD, 'I014554' AS SAP_ESP, '84439949' AS NCM_ESP, '2' AS EX_ESP FROM DUAL
    UNION ALL
    SELECT 'RV-002-00033' AS COD, 'I016735' AS SAP_ESP, '84439941' AS NCM_ESP, '' AS EX_ESP FROM DUAL
    UNION ALL
    SELECT 'RV-002-00041' AS COD, 'I014305' AS SAP_ESP, '84439950' AS NCM_ESP, '' AS EX_ESP FROM DUAL
    UNION ALL
    SELECT 'RV-002-00132' AS COD, 'I014304' AS SAP_ESP, '84439950' AS NCM_ESP, '' AS EX_ESP FROM DUAL
    UNION ALL
    SELECT 'RV-002-00154' AS COD, 'I016497' AS SAP_ESP, '84439950' AS NCM_ESP, '' AS EX_ESP FROM DUAL
    UNION ALL
    SELECT 'RV-002-00166' AS COD, 'I100194' AS SAP_ESP, '84433299' AS NCM_ESP, '9' AS EX_ESP FROM DUAL
    UNION ALL
    SELECT 'RV-002-00167' AS COD, 'I014539' AS SAP_ESP, '84439949' AS NCM_ESP, '2' AS EX_ESP FROM DUAL
    UNION ALL
    SELECT 'RV-002-00168' AS COD, 'I014523' AS SAP_ESP, '84433299' AS NCM_ESP, '9' AS EX_ESP FROM DUAL
    UNION ALL
    SELECT 'RV-002-00171' AS COD, 'I016148' AS SAP_ESP, '84439950' AS NCM_ESP, '' AS EX_ESP FROM DUAL
) E
LEFT JOIN SB1010 B1
       ON TRIM(B1.B1_COD) = E.COD
      AND B1.D_E_L_E_T_ <> '*'
ORDER BY E.COD, B1.B1_FILIAL
